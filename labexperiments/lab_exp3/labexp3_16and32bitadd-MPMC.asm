DATA SEGMENT
ARR DW 0002H, 0003H, 0004H
N   DW 3
SUM DD 0
DATA ENDS

CODE SEGMENT
ASSUME CS:CODE, DS:DATA

START:
    MOV AX, DATA
    MOV DS, AX

    MOV SI, OFFSET ARR
    MOV CX, N
    MOV AX, 0000H
    MOV DX, 0000H

L1:
    ADD AX, [SI]
    ADC DX, 0000H
    ADD SI, 2
    LOOP L1

    MOV WORD PTR SUM, AX
    MOV WORD PTR SUM+2, DX

    HLT

CODE ENDS
END START